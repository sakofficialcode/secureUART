"""Generate syn/gls_init.do from syn/out/top_scan.v.

Gate-level X-pessimism: the ARM cell models start every flop at X, and some
synthesized reset logic (e.g. uart_rx bit_cnt: D = !(q | !q) during reset)
evaluates X | !X = X, so the flop never leaves X even though real silicon
always resets it. Real flops power up to 0 or 1, never X, so the .do file
deposits a random 0/1 on every flop output at 1 ns (before the first clock
edge); reset must then clear them, which the testbench checks.

Usage (re-run whenever the netlist changes):  python syn/gen_gls_init.py
"""
import re
from pathlib import Path

HERE = Path(__file__).parent
NETLIST = HERE / "out" / "top_scan.v"
OUT = HERE / "gls_init.do"
CHIPS = ["/top_tb/chip_a", "/top_tb/chip_b"]
SEED = 1

text = NETLIST.read_text()
modules = {m.group(1): m.group(2)
           for m in re.finditer(r"^module (\w+)\b(.*?)^endmodule", text, re.S | re.M)}

# Split a module body into cell instances: "<ref> <inst> ( ... );"
inst_re = re.compile(r"^\s+(\w+)\s+(\\?\S+)\s*\((.*?)\);", re.S | re.M)
flops = {}     # module -> [output net]
children = {}  # module -> [(inst, child module)]
for name, body in modules.items():
    flops[name], children[name] = [], []
    for ref, inst, conns in inst_re.findall(body):
        if ref in modules:
            children[name].append((inst, ref))
        elif "DFF" in ref:
            q = re.search(r"\.QN?\(\s*([^)\s]+)\s*\)", conns)
            if not q:
                raise SystemExit(f"{name}/{inst} ({ref}): no Q/QN connection")
            flops[name].append(q.group(1))


def walk(mod, path):
    for net in flops[mod]:
        yield f"{path}/{net}"
    for inst, child in children[mod]:
        yield from walk(child, f"{path}/{inst}")


nets = list(walk("top", ""))
if len(nets) != 132:
    raise SystemExit(f"expected 132 flops, found {len(nets)}")

lines = [
    "# GENERATED by syn/gen_gls_init.py from syn/out/top_scan.v -- do not edit.",
    f"# Deposits a random 0/1 on all {len(nets)} flop outputs per chip at 1 ns.",
    f"expr {{srand({SEED})}}",
    "run 1ns",
]
for chip in CHIPS:
    lines += [f"force -deposit {{{chip}{n}}} [expr {{int(rand()*2)}}]" for n in nets]
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT} ({len(nets)} flops x {len(CHIPS)} chips)")
